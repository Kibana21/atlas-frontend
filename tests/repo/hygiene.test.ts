/** Repository rules that need no network (CI `security`): secrets, workflows, toolchain pins, safe code. */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const tracked = execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8" })
  .split("\n")
  .filter(Boolean);
const read = (file: string) => readFileSync(join(ROOT, file), "utf8");
const SELF = "tests/repo/hygiene.test.ts";

const SECRET_PATTERNS: Record<string, RegExp> = {
  "aws access key": /AKIA[0-9A-Z]{16}/,
  "github token": /\b(ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}/,
  "private key": /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  "slack token": /xox[abprs]-[A-Za-z0-9-]{10,}/,
  "password in url": /[a-z+]+:\/\/[^:/\s"'`]+:(?!\$\{[A-Za-z_][A-Za-z0-9_]*\}@|pw@|x@)[^@\s"'`]{4,}@/,
};

describe("repository hygiene", () => {
  it("tracks no env files or keys (only .env.example)", () => {
    expect(
      tracked.filter((f) => /(^|\/)(\.env(\..+)?|.*\.pem|.*\.key|id_rsa.*)$/.test(f) && f !== ".env.example"),
    ).toEqual([]);
  });

  it("contains no secret patterns in tracked files", () => {
    const hits = tracked
      .filter((f) => f !== SELF && f !== "pnpm-lock.yaml")
      .flatMap((f) => {
        const text = read(f);
        return Object.entries(SECRET_PATTERNS)
          .filter(([, rx]) => rx.test(text))
          .map(([kind]) => `${f}: ${kind}`);
      });
    expect(hits).toEqual([]);
  });

  it("pins Node and pnpm exactly, the same everywhere", () => {
    const pkg = JSON.parse(read("package.json")) as {
      engines: Record<string, string>;
      packageManager: string;
    };
    const nvmrc = read(".nvmrc").trim();
    expect(nvmrc).toMatch(/^24\.\d+\.\d+$/);
    expect(pkg.engines.node).toBe(nvmrc);
    expect(pkg.packageManager).toMatch(/^pnpm@\d+\.\d+\.\d+\+sha512\.[0-9a-f]{128}$/);
    expect(pkg.packageManager.startsWith(`pnpm@${pkg.engines.pnpm}+`)).toBe(true);
    expect(read(".npmrc")).toContain("engine-strict=true");
  });

  it("workflows: read-only permissions, SHA-pinned actions, no pull_request_target, Node from .nvmrc", () => {
    const workflows = tracked.filter((f) => f.startsWith(".github/workflows/"));
    expect(workflows.length).toBeGreaterThan(0);
    for (const wf of workflows) {
      const text = read(wf);
      expect(text).not.toContain("pull_request_target");
      expect(text).toMatch(/^permissions: \{\}$/m);
      for (const [, uses] of text.matchAll(/uses:\s*(\S+)/g)) expect(uses).toMatch(/@[0-9a-f]{40}$/);
      expect([...text.matchAll(/node-version:\s/g)], `${wf}: Node must come from .nvmrc`).toHaveLength(0);
      if (text.includes("setup-node")) expect(text).toContain("node-version-file: .nvmrc");
    }
  });

  it("E2E acceptance specs never intercept or mock requests (AC-16)", () => {
    const specs = tracked.filter((f) => f.startsWith("e2e/") && f.endsWith(".ts"));
    expect(specs.length).toBeGreaterThan(0);
    for (const file of specs) {
      expect(read(file), file).not.toMatch(/\.route\(|routeFromHAR|\.fulfill\(|setOffline\(/);
    }
  });

  it("source never injects raw HTML, evaluates strings or hard-codes colours", () => {
    const source = tracked.filter(
      (f) =>
        /^src\/.*\.(ts|tsx)$/.test(f) &&
        !f.startsWith("src/generated/") &&
        !f.endsWith(".test.ts") &&
        !f.endsWith(".test.tsx"),
    );
    for (const file of source) {
      const text = read(file);
      expect(text, file).not.toMatch(/dangerouslySetInnerHTML|\beval\(|new Function\(|innerHTML\s*=/);
      expect(text.replace(/d="[^"]*"/g, ""), file).not.toMatch(/#[0-9a-fA-F]{6}\b|rgba?\(/);
    }
  });

  it("generated files carry the do-not-edit header", () => {
    expect(read("src/generated/api/schema.d.ts")).toMatch(
      /GENERATED by scripts\/gen-api\.mjs[\s\S]*DO NOT EDIT/,
    );
    expect(read("src/styles/tokens.generated.css")).toMatch(/DO NOT EDIT/);
  });
});
