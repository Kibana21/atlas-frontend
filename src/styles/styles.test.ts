import { readFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const tokens = readFileSync(join(root, "src/styles/tokens.generated.css"), "utf8");
const base = readFileSync(join(root, "src/styles/base.css"), "utf8");

describe("generated tokens (FR-51, F-04)", () => {
  it("carries the do-not-edit header with the pinned specs commit", () => {
    expect(tokens).toMatch(/GENERATED by scripts\/gen-tokens\.mjs/);
    expect(tokens).toMatch(/at [0-9a-f]{40} \(contract-v0\.1\.0\)\. DO NOT EDIT/);
  });

  it("defines all 95 tokens and maps the Tailwind theme only onto them", () => {
    expect(tokens.match(/^ {2}--atlas-[a-z0-9-]+: /gm)).toHaveLength(95);
    const theme = tokens.slice(tokens.indexOf("@theme inline {"));
    expect(theme).toContain("--color-*: initial;");
    for (const line of theme.split("\n").filter((l) => /^ {2}--[a-z]/.test(l) && !l.includes("initial"))) {
      expect(line).toMatch(/: var\(--atlas-[a-z0-9-]+\);$/);
    }
    expect(theme).toContain("--color-brand-primary: var(--atlas-color-brand-primary);");
    expect(theme).toContain("--color-entity-api-text: var(--atlas-color-entity-api-text);");
  });
});

describe("base styles (FR-54, AR-05, AR-10, spec 7.3)", () => {
  it("is light only, with no dark-mode rules", () => {
    expect(base).toContain("color-scheme: light");
    expect(base).not.toContain("prefers-color-scheme");
  });

  it("has the 2 px focus ring with 2 px offset from tokens", () => {
    expect(base).toMatch(
      /:focus-visible \{\s*outline: var\(--atlas-focus-ring-width\) solid var\(--atlas-color-focus-ring\);\s*outline-offset: var\(--atlas-focus-ring-offset\);/,
    );
  });

  it("removes motion under prefers-reduced-motion and keeps focus visible in forced colours", () => {
    const reduced = base.slice(base.indexOf("@media (prefers-reduced-motion: reduce)"));
    for (const rule of ["animation-duration", "transition-duration", "transform", "scroll-behavior: auto"]) {
      expect(reduced).toContain(rule);
    }
    expect(base).toContain("@media (forced-colors: active)");
  });

  it("never hard-codes a colour", () => {
    expect(base.replaceAll(/var\(--atlas-[a-z0-9-]+\)/g, "")).not.toMatch(/#[0-9a-fA-F]{3,8}\b|rgb\(/);
  });
});
