// `pnpm gen:tokens` (ATLAS-001 FR-51): design/tokens.json (pinned atlas-specs) -> src/styles/tokens.generated.css
// 1. every token as a CSS custom property `--atlas-<path>` on :root;
// 2. the Tailwind v4 theme mapped onto those properties. Tailwind's default colour, spacing, radius and
//    shadow scales are reset, so only token-backed utilities exist (no hard-coded colours).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { readLock } from "./specs.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function flatten(node, path = [], out = []) {
  if (node && typeof node === "object" && "value" in node) {
    out.push([path.join("-"), String(node.value)]);
    return out;
  }
  if (node && typeof node === "object") {
    for (const [key, child] of Object.entries(node)) flatten(child, [...path, key], out);
  }
  return out;
}

const THEME = [
  // [Tailwind namespace prefix, token path prefix]
  ["--color-", "color-"],
  ["--font-", "typography-font-family-"],
  ["--text-", "typography-size-"],
  ["--font-weight-", "typography-weight-"],
  ["--leading-", "typography-line-height-"],
  ["--spacing-", "space-"],
  ["--spacing-", "size-"],
  ["--radius-", "radius-"],
  ["--shadow-elevation-", "elevation-"],
  ["--ease-", "motion-easing-"],
];

export function render(tokens, lock) {
  const flat = [];
  for (const [group, value] of Object.entries(tokens)) {
    if (!["meta", "thresholds", "contrast_pairs"].includes(group)) flatten(value, [group], flat);
  }
  flat.sort(([a], [b]) => a.localeCompare(b));
  const lines = [
    "/*",
    " * GENERATED by scripts/gen-tokens.mjs from atlas-specs design/tokens.json",
    ` * at ${lock.specs_commit} (contract-v${lock.contract_version}). DO NOT EDIT: run \`pnpm gen\`.`,
    ` * ${flat.length} tokens; status: ${tokens.meta?.status ?? "unknown"} (${tokens.meta?.decision ?? ""}).`,
    " */",
    "",
    ":root {",
    ...flat.map(([name, value]) => `  --atlas-${name}: ${value};`),
    "}",
    "",
    "@theme inline {",
    "  --color-*: initial;",
    "  --spacing-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --font-*: initial;",
    "  --text-*: initial;",
    "  --font-weight-*: initial;",
    "  --leading-*: initial;",
    "  --ease-*: initial;",
  ];
  for (const [namespace, prefix] of THEME) {
    for (const [name] of flat) {
      if (name.startsWith(prefix))
        lines.push(`  ${namespace}${name.slice(prefix.length)}: var(--atlas-${name});`);
    }
  }
  lines.push("}", "");
  return { css: lines.join("\n"), count: flat.length };
}

export function generate(outFile = join(ROOT, "src", "styles", "tokens.generated.css")) {
  const lock = readLock(readFileSync(join(ROOT, "specs.lock"), "utf8"));
  const tokens = JSON.parse(readFileSync(join(ROOT, "build", "specs", "design", "tokens.json"), "utf8"));
  const { css, count } = render(tokens, lock);
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, css);
  return count;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const count = generate(process.argv[2]);
  console.log(`OK: ${count} tokens -> ${process.argv[2] ?? "src/styles/tokens.generated.css"}`);
}
