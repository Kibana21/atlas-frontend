// `pnpm gen:api` (ATLAS-001 FR-51): the pinned contract -> src/generated/api/schema.d.ts (openapi-typescript).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

import { readLock } from "./specs.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export async function generate(outFile = join(ROOT, "src", "generated", "api", "schema.d.ts")) {
  const lock = readLock(readFileSync(join(ROOT, "specs.lock"), "utf8"));
  const contract = join(ROOT, "build", "specs", "contracts", "openapi", "atlas-api.yaml");
  const ast = await openapiTS(pathToFileURL(contract), { alphabetize: true });
  const header = [
    "/*",
    " * GENERATED by scripts/gen-api.mjs (openapi-typescript) from atlas-specs contracts/openapi/atlas-api.yaml",
    ` * at ${lock.specs_commit} (contract-v${lock.contract_version}). DO NOT EDIT: run \`pnpm gen\`.`,
    " */",
    "",
  ].join("\n");
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, header + astToString(ast));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generate(process.argv[2]);
  console.log(`OK: API types -> ${process.argv[2] ?? "src/generated/api/schema.d.ts"}`);
}
